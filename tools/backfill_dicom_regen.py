#!/usr/bin/env python3
"""backfill_dicom_regen.py — data-office backfill for no-DICOM MRI placeholders.

THE missing piece of the no-DICOM regeneration story (2026-07-16): a
worklist-driven pass that FILLS the empty `<ACQ-ID>.data/` placeholders in
/raw/ from the staged ParaVision sources, keeping each acquisition's existing
ACQ-ID. This is the `recover_subject_metadata.py` recovery pattern — a
controlled in-place update of an already-registered acquisition — NOT a
re-ingest: the ingest's dedup would skip every registered row, and bypassing
the dedup would mint a NEW ACQ-ID and append a duplicate registry row (the
design trap this tool exists to avoid; see
tasks/dicom_regen_backfill_handoff.md §4.1).

WHAT IT DOES (per worklist row with status=="pending")
    1. locate the staged source exam under --staging
       (`<staging>/PV<paravision_version>/<study>/<exam>` from `original_name`
       — staged read-only from the platform host by
       tools/pull_pending_dicom_sources.py);
    2. re-check it is really an image exam (`is_nonimage_exam`) — a
       spectroscopy/calibration row is corrected to "not-applicable", exactly
       as the live ingest queue site classifies;
    3. regenerate + copy via the SAME code path as an ingest-time regen —
       `ingest_raw.copy_mri_paravision(..., auto_regenerate_dicom=True)`
       (Dicomifier + the two PV-7 workarounds; per-file sha256 verify during
       copy) — into the EXISTING `<ACQ-ID>.data/`, so the result is
       byte-identical to what a Dicomifier-equipped ingest would have written;
    4. VERIFY-after-write: re-hash every file on disk against the copy-time
       checksums AND run the PixelSpacing axis-order validation
       (validate_dicomifier_pixelspacing). On failure the freshly written
       DICOMs are removed (the placeholder is restored) and the row stays
       pending — `.data/` populated always implies verified data;
    5. refresh the acquisition's bookkeeping: checksums.json (was empty),
       sidecar `subject.age_at_acquisition` (blank-only fill, derived from
       date_of_birth + the now-real acquisition date — closes the last of the
       2026-07-15 age bug), README.txt (the three stale lines only);
    6. update the REGISTRY ROW in place (registry.update_row, the capability
       added for this tool): file_count / file_size_mb / checksum_present, and
       — blank-only — acquisition_datetime (from the regenerated DICOM's
       StudyDate+StudyTime) and file_format. NEVER overwrites a real value;
    7. flip the worklist row to status="regenerated". Steps 6-7 run inside ONE
       registry_lock critical section, so a crash never leaves the registry
       and the worklist disagreeing about a completed exam.

CRASH RECOVERY / RECONCILE. If a previous --apply run died between steps 3
and 7, the row is still "pending" but its `.data/` is populated. Such a row is
NOT regenerated again (never touch existing data): it is RECONCILED — the
on-disk DICOMs are re-verified (hash + PixelSpacing) and steps 5-7 completed
from what is on disk.

THE 94 NO-SOURCE ROWS. A pending row whose staged source has NO
`pdata/<idx>/2dseq` anywhere cannot be regenerated by Dicomifier — ever (80
header-only + 14 fid-only exams, verified 2026-07-16). They are reported, and
flipped to the terminal status "no-source" ONLY under the explicit
--mark-no-source flag (a human-gated call, mirroring the precedent's
"never auto-mark unresolvable"); without the flag they just stay pending.

SAFEGUARDS (mirroring recover_subject_metadata.py)
    * DRY-RUN by default — reports what WOULD happen, touches NOTHING
      (no Dicomifier runs either). Writing requires --apply.
    * Controlled write — registry fields that can already hold a real value
      (acquisition_datetime, file_format) are filled ONLY when blank; the
      sidecar fill touches ONLY a blank subject.age_at_acquisition.
    * VERIFY-AFTER-WRITE with rollback (step 4) before any bookkeeping.
    * IDEMPOTENT — rows already regenerated / not-applicable / no-source are
      skipped; a populated pending row reconciles instead of re-regenerating.
    * One-exam error isolation — a failure is recorded and the walk continues.

Usage (regeneration itself must run from WSL — Dicomifier is Linux/conda;
see the runbook / 11_OPERATIONS: `conda activate dicomifier-pilot`):

    # Preview everything (safe anywhere, no Dicomifier needed):
    PYTHONPATH=tools python tools/backfill_dicom_regen.py

    # Regenerate one exam as a pilot, then the rest (from WSL):
    PYTHONPATH=tools python tools/backfill_dicom_regen.py --apply --limit 1
    PYTHONPATH=tools python tools/backfill_dicom_regen.py --apply

    # Record the un-regenerable rows (data-office decision 2026-07-16):
    PYTHONPATH=tools python tools/backfill_dicom_regen.py --apply --mark-no-source

    # After a WSL --apply run: rebuild project hard-links FROM WINDOWS
    # (os.link is refused over the CIFS mount from WSL):
    python tools/relink_mri_regen.py --nas-root J:/gjesus3-data

NOTE: the sidecar's `mri:` block is deliberately NOT rewritten — it faithfully
carries the JCAMP-DX parse from ingest time, which is unchanged by the regen;
the per-frame DICOM headers now live in the DICOMs themselves in `.data/`.
"""

