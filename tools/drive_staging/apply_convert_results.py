"""After convert_staged_exams.py: keep only had-dicom/converted rows in a batch's case table;
append the not-registered ones (with status + reason) to its excluded_*.csv; add the per-row
drv_dicom_origin note. usage: apply_convert.py <config basename>"""
import sys, os, pandas as pd
CFG = r"C:\Users\rtasseff\OneDrive - CIC biomaGUNE\projects\DataInfra\gjesus3-archive\gjesus3-dev\drives-dicom\tools\configs\drives_2026-09\dicom"
name = sys.argv[1]; batch = name.split("_")[1]
cases = os.path.join(CFG, f"cases_{name}.csv")
conv = pd.read_csv(os.path.join(CFG, f"convert_{batch}.csv"), dtype=str, keep_default_na=False)
d = pd.read_csv(cases, dtype=str, keep_default_na=False)
m = d.merge(conv, on="original_name", how="left")
assert m.status.notna().all() and (m.status != "").all(), "convert result missing for some rows"
keep = m[m.status.isin(["had-dicom", "converted"])].copy()
keep["drv_dicom_origin"] = keep.status.map({"had-dicom": "scanner-exported DICOM",
                                            "converted": "DICOM regenerated by Dicomifier 2.5.3 (+ gjesus3 workarounds) from the ParaVision 2dseq before ingest"})
drop = m[~m.status.isin(["had-dicom", "converted"])]
keep[list(d.columns) + ["drv_dicom_origin"]].to_csv(cases, index=False, encoding="utf-8")
ex = os.path.join(CFG, f"excluded_{name}.csv")
old = pd.read_csv(ex, dtype=str, keep_default_na=False) if os.path.exists(ex) else pd.DataFrame(columns=["original_name", "reason"])
new = drop.assign(reason=drop.status + ": " + drop.reason)[["original_name", "reason"]]
pd.concat([old, new], ignore_index=True).drop_duplicates("original_name").to_csv(ex, index=False, encoding="utf-8")
print(f"{name}: kept {len(keep)} ({keep.status.value_counts().to_dict()}); not registered {len(drop)} {drop.status.value_counts().to_dict()}")
